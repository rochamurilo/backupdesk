$ErrorActionPreference='Stop'
$ProgressPreference='SilentlyContinue'
try{
 $phase='identity'
 $sid=$env:BACKUPDESK_VSS_OWNER_SID;$product=$env:BACKUPDESK_VSS_PRODUCT
 if($sid -notmatch '^S-1-(?:\d+-)+\d+$' -or $product -notin @('master','client')){throw 'Identificação da instalação VSS inválida.'}
 $null=New-Object System.Security.Principal.SecurityIdentifier($sid)
 $principal=New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
 if(-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)){throw 'Autorize a instalação do componente VSS como administrador.'}
 if($env:BACKUPDESK_UPDATE_DIR){
  $phase='stop-application'
  . (Join-Path $PSScriptRoot 'update-application.ps1')
  Stop-BackupDeskInstallation $env:BACKUPDESK_UPDATE_DIR
  if($env:BACKUPDESK_VSS_REMOVE -eq '1'){Remove-BackupDeskStartup $sid $product}else{Register-BackupDeskStartup $env:BACKUPDESK_UPDATE_DIR $sid $product}
 }
 $taskName='BackupDeskVSS-'+$product+'-'+$sid
 $phase='stop-existing'
 $existing=Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
 if($existing){
  Stop-ScheduledTask -TaskName $taskName -ErrorAction Stop
  for($i=0;$i -lt 40;$i++){if((Get-ScheduledTask -TaskName $taskName).State -ne 'Running'){break};Start-Sleep -Milliseconds 250}
  if((Get-ScheduledTask -TaskName $taskName).State -eq 'Running'){throw 'O componente VSS anterior ainda está parando.'}
 }
 $state=Join-Path $PSScriptRoot ('state\'+$sid)
 if($env:BACKUPDESK_VSS_REMOVE -eq '1'){
  if($existing){Unregister-ScheduledTask -TaskName $taskName -Confirm:$false}
  # Only clean ledgers generated by this component, never arbitrary Windows snapshots.
  if(Test-Path -LiteralPath $state){foreach($ledger in Get-ChildItem -LiteralPath $state -Filter '*.json'){
   if($ledger.BaseName -match '^[a-f0-9]{64}$'){
    $env:BACKUPDESK_VSS_REQUEST='{"action":"cleanup"}';$env:BACKUPDESK_VSS_LEDGER=$ledger.FullName
    & (Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe') -NoLogo -NoProfile -NonInteractive -File (Join-Path $PSScriptRoot 'vss.ps1')
    if($LASTEXITCODE -ne 0){throw 'Não foi possível limpar os snapshots desta instalação.'}
   }
  };Remove-Item -LiteralPath $state -Recurse -Force}
  exit 0
 }
 # The SYSTEM task only executes these protected files, never scripts in AppData.
 $phase='protect-files'
 $acl=New-Object System.Security.AccessControl.DirectorySecurity
 $admins=New-Object System.Security.Principal.SecurityIdentifier('S-1-5-32-544')
 $system=New-Object System.Security.Principal.SecurityIdentifier('S-1-5-18')
 $acl.SetOwner($admins);$acl.SetAccessRuleProtection($true,$false)
 foreach($identity in @($admins,$system)){
  $acl.AddAccessRule((New-Object System.Security.AccessControl.FileSystemAccessRule($identity,'FullControl','ContainerInherit,ObjectInherit','None','Allow')))
 }
 Set-Acl -LiteralPath $PSScriptRoot -AclObject $acl
 $phase='create-state'
 New-Item -ItemType Directory -Path $state -Force | Out-Null
 $ready=Join-Path $state 'ready.json';Remove-Item -LiteralPath $ready -Force -ErrorAction SilentlyContinue
 $exe=Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
 $arguments='-NoLogo -NoProfile -NonInteractive -ExecutionPolicy Bypass -File "'+(Join-Path $PSScriptRoot 'vss-broker.ps1')+'" -UserSid '+$sid+' -Product '+$product
 $action=New-ScheduledTaskAction -Execute $exe -Argument $arguments
 $trigger=@((New-ScheduledTaskTrigger -AtStartup),(New-ScheduledTaskTrigger -AtLogOn -User $sid))
 $account=New-ScheduledTaskPrincipal -UserId 'S-1-5-18' -LogonType ServiceAccount -RunLevel Highest
 $settings=New-ScheduledTaskSettingsSet -ExecutionTimeLimit ([TimeSpan]::Zero) -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1) -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew -StartWhenAvailable
 $phase='register-task'
 Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Principal $account -Settings $settings -Description 'Componente VSS do BackupDesk. Permite snapshots sem elevar o painel ou o agente.' -Force | Out-Null
 # The installation user may query/run this fixed SYSTEM task, never edit its action or permissions.
 # Administrators own the task so a filtered token of its creator gains no implicit WRITE_DAC.
 $phase='task-access'
 $scheduler=New-Object -ComObject 'Schedule.Service';$scheduler.Connect()
 $registered=$scheduler.GetFolder('\').GetTask($taskName)
 $registered.SetSecurityDescriptor(('O:BAG:BAD:P(A;;GA;;;SY)(A;;GA;;;BA)(A;;GRGX;;;'+$sid+')'),0)
 Enable-ScheduledTask -TaskName $taskName | Out-Null
 $phase='start-task'
 Start-ScheduledTask -TaskName $taskName
 for($i=0;$i -lt 60;$i++){if(Test-Path -LiteralPath $ready){exit 0};Start-Sleep -Milliseconds 250}
 $log=Join-Path $state 'broker.log';$details='';if(Test-Path -LiteralPath $log){$details=(Get-Content -LiteralPath $log -Tail 4) -join '; '}
 throw ('O componente VSS foi registrado, mas não iniciou. '+$details)
}catch{[Console]::Error.WriteLine(('VSS setup ['+$phase+']: '+$_.Exception.Message+' '+$_.ScriptStackTrace));exit 1}
